@router.get("/query/{query_id}", summary="Download query answer as PDF")
async def download_query_pdf(
    query_id: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    """Generate and return a professional PDF for a specific AI query answer."""
    result = await db.execute(
        select(QueryHistory).where(
            QueryHistory.id == query_id,
            QueryHistory.user_id == current_user.id,
        )
    )
    query = result.scalar_one_or_none()
    if not query:
        raise HTTPException(status_code=404, detail="Query not found")

    pdf_bytes = _generate_query_pdf(query, current_user)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="sevasetu_query_{query_id}.pdf"',
            "X-Generated-By": "SevaSetu AI - Made in India",
        },
    )


@router.get("/history", summary="Download full history as PDF")
async def download_history_pdf(
    limit: int = 20,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user),
):
    """Generate PDF of user's query history (last N queries)."""
    result = await db.execute(
        select(QueryHistory)
        .where(QueryHistory.user_id == current_user.id)
        .order_by(desc(QueryHistory.created_at))
        .limit(limit)
    )
    queries = result.scalars().all()

    if not queries:
        raise HTTPException(status_code=404, detail="No query history found")

    pdf_bytes = _generate_history_pdf(queries, current_user)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": 'attachment; filename="sevasetu_history.pdf"',
        },
    )


@router.get("/checklist/{service_type}", summary="Download document checklist as PDF")
async def download_checklist_pdf(
    service_type: str,
    current_user: User = Depends(get_current_active_user),
):
    """Generate and download a styled document checklist PDF."""
    from ai.ocr.ocr_engine import ocr_engine
    checklist = ocr_engine.generate_checklist(service_type)
    pdf_bytes = _generate_checklist_pdf(checklist, current_user)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="sevasetu_checklist_{service_type}.pdf"',
        },
    )


# ── PDF BUILDERS ──────────────────────────────────────────────────────────────

def _generate_query_pdf(query: QueryHistory, user: User) -> bytes:
    """Build a single query answer PDF."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        rightMargin=20*mm, leftMargin=20*mm,
        topMargin=20*mm, bottomMargin=20*mm,
    )
    styles = _build_styles()
    elements = []

    # Header
    elements += _build_header(
        styles,
        title="Government Service Guidance",
        subtitle="AI-Generated Advisory by SevaSetu AI",
        user_name=user.name,
    )

    # Category badge
    cat = (query.category or "general").replace("_", " ").upper()
    cat_color = {
        "VOTER ID": SAFFRON, "PAN CARD": GREEN_IN, "PASSPORT": NAVY,
        "SCHEME": GOLD, "HEALTH SCHEME": GREEN_IN, "AGRICULTURE SCHEME": GREEN_IN,
    }.get(cat, NAVY)

    badge_data = [[Paragraph(f"📋 {cat}", styles["badge"])]]
    badge_table = Table(badge_data, colWidths=[40*mm])
    badge_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, 0), cat_color),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("ROUNDEDCORNERS", [8, 8, 8, 8]),
    ]))
    elements.append(badge_table)
    elements.append(Spacer(1, 8))

    # Question
    elements.append(Paragraph("❓ Your Question", styles["heading"]))
    q_data = [[Paragraph(query.question, styles["body"])]]
    q_table = Table(q_data, colWidths=[170*mm])
    q_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
        ("PADDING", (0, 0), (-1, -1), 10),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#FFE4CC")),
        ("ROUNDEDCORNERS", [6, 6, 6, 6]),
    ]))
    elements.append(q_table)
    elements.append(Spacer(1, 12))

    # AI Answer
    elements.append(Paragraph("🤖 SevaSetu AI Response", styles["heading"]))

    # Clean HTML tags from answer for PDF
    import re
    clean_answer = re.sub(r"<[^>]+>", "", query.ai_response)
    clean_answer = clean_answer.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")

    for para in clean_answer.split("\n"):
        para = para.strip()
        if para:
            elements.append(Paragraph(para, styles["body"]))

    elements.append(Spacer(1, 12))

    # Metadata table
    elements.append(Paragraph("📊 Query Information", styles["heading"]))
    meta_data = [
        ["Field", "Value"],
        ["Query ID", f"#{query.id}"],
        ["Category", query.category or "General"],
        ["Language", {"en": "English", "hi": "Hindi", "mr": "Marathi"}.get(query.language, "English")],
        ["AI Confidence", f"{int((query.confidence or 0) * 100)}%"],
        ["Asked On", datetime.fromisoformat(str(query.created_at)).strftime("%d %b %Y, %I:%M %p") if query.created_at else "N/A"],
    ]
    meta_table = Table(meta_data, colWidths=[50*mm, 120*mm])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, LIGHT_BG]),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(meta_table)

    # Footer
    elements += _build_footer(styles)

    doc.build(elements)
    return buffer.getvalue()


def _generate_checklist_pdf(checklist: dict, user: User) -> bytes:
    """Build a document checklist PDF with status indicators."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        rightMargin=20*mm, leftMargin=20*mm,
        topMargin=20*mm, bottomMargin=20*mm,
    )
    styles = _build_styles()
    elements = []

    elements += _build_header(
        styles,
        title=checklist.get("title", "Document Checklist"),
        subtitle="Required documents for your government service application",
        user_name=user.name,
    )

    # Info strip
    if checklist.get("online_portal"):
        elements.append(Paragraph(
            f"🌐 <b>Portal:</b> {checklist['online_portal']}   "
            f"📞 <b>Helpline:</b> {checklist.get('helpline', 'N/A')}   "
            f"📋 <b>Form:</b> {checklist.get('form', 'N/A')}   "
            f"💰 <b>Fee:</b> {checklist.get('fee', 'Free')}",
            styles["body"]
        ))
        elements.append(Spacer(1, 10))

    # Documents table
    elements.append(Paragraph("📋 Required Documents", styles["heading"]))

    table_data = [["#", "Document", "Status", "Purpose"]]
    status_colors = {
        "required": SAFFRON, "optional": NAVY,
        "completed": GREEN_IN, "conditional": GOLD,
    }

    for i, doc_item in enumerate(checklist.get("documents", []), 1):
        status = doc_item.get("status", "required")
        table_data.append([
            str(i),
            doc_item.get("name", ""),
            status.upper(),
            doc_item.get("purpose", ""),
        ])

    doc_table = Table(table_data, colWidths=[10*mm, 60*mm, 25*mm, 75*mm])
    doc_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, LIGHT_BG]),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (0, 0), (0, -1), "CENTER"),
        ("ALIGN", (2, 0), (2, -1), "CENTER"),
    ]))
    elements.append(doc_table)
    elements.append(Spacer(1, 12))

    # Tips
    elements.append(Paragraph("💡 Important Tips", styles["heading"]))
    tips = [
        "Carry both original and self-attested photocopies of all documents.",
        "Ensure all documents are in good condition and clearly readable.",
        "Check online portal for latest fee structure before applying.",
        "Keep a copy of acknowledgment / reference number after submission.",
        "For any issues, call the helpline number provided above.",
    ]
    for tip in tips:
        elements.append(Paragraph(f"• {tip}", styles["body"]))

    elements += _build_footer(styles)
    doc.build(elements)
    return buffer.getvalue()


def _generate_history_pdf(queries: list, user: User) -> bytes:
    """Build a history export PDF with all recent queries."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        rightMargin=20*mm, leftMargin=20*mm,
        topMargin=20*mm, bottomMargin=20*mm,
    )
    styles = _build_styles()
    elements = []

    elements += _build_header(
        styles,
        title="Query History Report",
        subtitle=f"Last {len(queries)} interactions with SevaSetu AI",
        user_name=user.name,
    )

    for i, q in enumerate(queries, 1):
        import re
        clean = re.sub(r"<[^>]+>", "", q.ai_response)[:300] + "..."

        block = [
            [Paragraph(f"<b>Q{i}. {q.question}</b>", styles["body"])],
            [Paragraph(clean, styles["small"])],
            [Paragraph(
                f"Category: {q.category or 'General'} | "
                f"Language: {q.language or 'en'} | "
                f"Confidence: {int((q.confidence or 0)*100)}% | "
                f"Date: {str(q.created_at)[:16]}",
                styles["small"]
            )],
        ]
        block_table = Table(block, colWidths=[170*mm])
        block_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG if i % 2 == 0 else WHITE),
            ("PADDING", (0, 0), (-1, -1), 8),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("TOPPADDING", (0, 0), (-1, 0), 10),
        ]))
        elements.append(block_table)
        elements.append(Spacer(1, 6))

    elements += _build_footer(styles)
    doc.build(elements)
    return buffer.getvalue()
