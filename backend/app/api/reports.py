# ── COLOUR PALETTE (India Tricolor inspired) ──────────────────────────────────

SAFFRON   = colors.HexColor("#FF6B00")
GREEN_IN  = colors.HexColor("#138808")
NAVY      = colors.HexColor("#003580")
GOLD      = colors.HexColor("#FFD700")
LIGHT_BG  = colors.HexColor("#FFF8F0")
DARK_TEXT = colors.HexColor("#1a1a2e")
GREY_TEXT = colors.HexColor("#6b7280")
WHITE     = colors.white
BLACK     = colors.black


def _build_styles():
    """Build custom ReportLab paragraph styles."""
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "Title", parent=base["Title"],
            fontSize=22, textColor=SAFFRON,
            fontName="Helvetica-Bold",
            alignment=TA_CENTER, spaceAfter=4,
        ),
        "subtitle": ParagraphStyle(
            "Subtitle", parent=base["Normal"],
            fontSize=11, textColor=GREY_TEXT,
            alignment=TA_CENTER, spaceAfter=16,
        ),
        "heading": ParagraphStyle(
            "Heading", parent=base["Heading2"],
            fontSize=13, textColor=NAVY,
            fontName="Helvetica-Bold",
            spaceBefore=12, spaceAfter=4,
            borderPad=4,
        ),
        "body": ParagraphStyle(
            "Body", parent=base["Normal"],
            fontSize=10, textColor=DARK_TEXT,
            leading=16, spaceAfter=6,
        ),
        "small": ParagraphStyle(
            "Small", parent=base["Normal"],
            fontSize=8, textColor=GREY_TEXT,
            leading=12,
        ),
        "footer": ParagraphStyle(
            "Footer", parent=base["Normal"],
            fontSize=8, textColor=GREY_TEXT,
            alignment=TA_CENTER,
        ),
        "badge": ParagraphStyle(
            "Badge", parent=base["Normal"],
            fontSize=9, textColor=WHITE,
            fontName="Helvetica-Bold",
            alignment=TA_CENTER,
        ),
    }


def _build_header(styles: dict, title: str, subtitle: str, user_name: str) -> list:
    """Build standard PDF header with SevaSetu AI branding."""
    elements = []

    # Logo / brand row
    header_data = [[
        Paragraph(
            '<font color="#FF6B00"><b>SevaSetu AI</b></font>'
            ' <font color="#6b7280" size="9">🇮🇳 Made in India</font>',
            styles["body"]
        ),
        Paragraph(
            f'<font color="#6b7280" size="8">Generated: '
            f'{datetime.now().strftime("%d %b %Y, %I:%M %p")}</font>',
            ParagraphStyle("R", fontSize=8, textColor=GREY_TEXT, alignment=TA_RIGHT)
        ),
    ]]
    header_table = Table(header_data, colWidths=[100*mm, 80*mm])
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(header_table)
    elements.append(HRFlowable(width="100%", thickness=2, color=SAFFRON, spaceAfter=12))

    # Main title
    elements.append(Paragraph(title, styles["title"]))
    elements.append(Paragraph(subtitle, styles["subtitle"]))

    # User info strip
    user_strip_data = [[
        Paragraph(f"<b>Citizen:</b> {user_name}", styles["small"]),
        Paragraph(f"<b>By:</b> Rahul Jha | <b>SevaSetu AI v1.0</b>", styles["small"]),
    ]]
    user_strip = Table(user_strip_data, colWidths=[90*mm, 90*mm])
    user_strip.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("ROUNDEDCORNERS", [4, 4, 4, 4]),
    ]))
    elements.append(user_strip)
    elements.append(Spacer(1, 10))
    return elements


def _build_footer(styles: dict) -> list:
    """Build standard disclaimer footer."""
    elements = [
        HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e5e7eb"), spaceBefore=16),
        Paragraph(
            "⚠️ <b>Disclaimer:</b> This document is generated by SevaSetu AI for informational purposes only. "
            "For official guidance, please visit the respective government portals or contact nearest government office. "
            "Information is subject to change. | Developed by Rahul Jha | Made in India 🇮🇳",
            styles["footer"]
        ),
    ]
    return elements


